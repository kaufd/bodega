package ru.kaufd.bodega.domain

/**
 * Официальная классификация вина по трём независимым измерениям.
 * Значения — отображаемые и хранимые строки (латиница для игристого).
 * Шкала сладости зависит от типа: см. [sweetnessByType].
 */
object WineClassification {
    val types = listOf("Тихое", "Игристое", "Креплёное")

    val colors = listOf("Красное", "Белое", "Розовое")

    val sweetnessByType: Map<String, List<String>> = mapOf(
        "Тихое" to listOf("Сухое", "Полусухое", "Полусладкое", "Сладкое"),
        "Игристое" to listOf("Brut", "Extra Dry", "Dry", "Полусладкое"),
        "Креплёное" to listOf("Сухое", "Полусладкое", "Сладкое"),
    )

    /**
     * Температура подачи — диапазоны из постов паблика (16-18 у красного, 10-12 у белого,
     * 6-8 у игристого покрывают три четверти случаев). Набор закрытый: своё значение
     * ввести нельзя, ближайший диапазон всегда находится.
     */
    val servingTemps = listOf(
        "6-8°С", "8-10°С", "10-12°С", "12-14°С", "14-16°С", "16-18°С", "18-20°С", "20-22°С",
    )

    /** Допустимые значения сладости для выбранного типа; пусто, если тип не выбран. */
    fun sweetnessFor(wineType: String?): List<String> =
        wineType?.let { sweetnessByType[it] } ?: emptyList()

    /** Все значения сладости в каноническом порядке (для сортировки фасетов фильтра). */
    val allSweetness: List<String> = sweetnessByType.values.flatten().distinct()
}
