package ru.kaufd.bodega.domain

/**
 * Почему облачное распознавание не удалось. Различаем то, на что пользователь
 * может повлиять по-разному: проверить ключ, пополнить счёт, подождать.
 */
enum class RecognitionError {
    /** Облачное распознавание выключено или не настроено. */
    DISABLED,

    /** Ключ неверен или отозван (401/403). */
    AUTH,

    /** Кончились кредиты (402). */
    CREDITS,

    /** Модель не подошла: опечатка в имени или она не принимает изображения (400/404). */
    MODEL,

    /** Слишком часто или провайдер недоступен (429/5xx). */
    BUSY,

    /** Нет сети, таймаут, оборванное соединение. */
    NETWORK,

    /** Про этот напиток в сети ничего не нашлось — черновику не на что опереться. */
    NO_DATA,

    /** Всё остальное, включая нечитаемый ответ. */
    OTHER,
}

class RecognitionException(val error: RecognitionError) : Exception(error.name)
