package ru.kaufd.bodega.domain

/**
 * Черновик заметки о вкусе по полям записи.
 *
 * Заметку пишет модель, а пост для публикации по-прежнему собирает [buildPostText]
 * из полей записи: формат снят с реальных постов и генерации не подлежит.
 */
interface DraftWriter {
    /**
     * [examples] — прежние заметки автора. Без них модель пишет обобщённым
     * «винным» языком, который в журнале выглядит чужеродно.
     *
     * Отказ — всегда [RecognitionException] с конкретной причиной, пустой строки
     * не возвращает: иначе каждый вызывающий изобретал бы своё правило для пустоты.
     */
    suspend fun draftNote(entry: Entry, examples: List<String>): String
}
